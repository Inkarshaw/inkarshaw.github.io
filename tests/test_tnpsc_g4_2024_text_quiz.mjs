/* Integrity gate: TNPSC 2024 Group IV text-based full 200 PYQ attempt. */
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
const read=path=>readFileSync(new URL('../'+path,import.meta.url),'utf8');
const bank=JSON.parse(read('data/quizzes/tnpsc-g4-2024-text-quiz.json'));
const source=JSON.parse(read('data/quizzes/tnpsc-g4-2024-original-questions.json'));
const official=JSON.parse(read('data/quizzes/original-final-keys.json')).papers.find(x=>x.id===bank.paperId);
const html=read('pyq-2024-text-quiz.html');
const js=read('assets/js/pyq-2024-text-quiz.js');
const hub=read('pyq-hub.html');
assert.equal(bank.paperId,'tnpsc-group-iv-2024-general-tamil-general-studies');
assert.equal(bank.year,2024);
assert.equal(bank.questionCount,200);
assert.equal(bank.completeTextCount,200);
assert.equal(bank.questions.length,200);
assert.equal(bank.manuallySourceVerifiedTextCount,0,'Text source review remains explicitly pending');
assert.equal(source.questions.length,200);
assert.equal(official.answers.length,200);
let special=0;
for(let i=0;i<200;i++){
 const q=bank.questions[i];
 assert.equal(q.number,i+1,'Original question number and position');
 assert.ok(q.question.trim().length>=3,'Question '+(i+1)+' has typed text');
 assert.deepEqual(Object.keys(q.options),['A','B','C','D','E']);
 assert.ok('ABCDE'.split('').every(letter=>typeof q.options[letter]==='string'&&q.options[letter].trim()),'Q'+(i+1)+' all five answer choices');
 assert.equal(q.finalKeyToken,official.answers[i],'Q'+(i+1)+' official final key match');
 assert.equal(q.finalKeyToken,source.questions[i].finalKeyToken,'Q'+(i+1)+' original source key match');
 assert.equal(q.sourcePdfPage,source.questions[i].sourcePdfPage,'Q'+(i+1)+' source PDF page match');
 assert.deepEqual(q.correctAnswers,q.finalKeyToken==='ALL'?[]:q.finalKeyToken.split('/'));
 assert.equal(q.sourceTextStatus,'typed_transcription_unverified_against_scan','No unearned claim of text verification');
 assert.equal(q.answerVerificationStatus,'reconciled_to_official_final_key');
 assert.equal(q.keyDisagreement,false);
 assert.ok(q.typedReferenceURL.startsWith('https://www.tnpscguide.com/exams/group-4/papers/group-4-2024-question-paper'));
 if(q.finalKeyToken==='ALL')special++;
}
assert.equal(special,4);
assert.ok(bank.questions.slice(0,100).every(q=>q.language==='ta'));
assert.ok(bank.questions.slice(100).every(q=>q.language==='en'));
assert.match(hub,/pyq-2024-text-quiz\.html/);
assert.match(hub,/Start 200-question text quiz/);
assert.match(html,/id="setup"/);
assert.match(html,/id="quiz"/);
assert.match(html,/id="results"/);
assert.match(html,/id="palette"/);
assert.match(html,/id="feedback"/);
assert.match(html,/editorial transcription/);
assert.match(html,/no PDF upload required/i);
assert.match(js,/200-question/);
assert.match(js,/clearexams:tnpsc:g4:2024:text200/);
assert.match(js,/current.+/,'Original question controls');
assert.match(js,/finalKeyToken/);
assert.ok(!js.includes('innerHTML'),'Do not insert untrusted source strings as HTML');
const ids=[...html.matchAll(/id="([^"]+)"/g)].map(x=>x[1]);
assert.equal(ids.length,new Set(ids).size,'No duplicate HTML IDs');
const used=[...js.matchAll(/\$\('([^']+)'\)/g)].map(x=>x[1]);
for(const id of used)assert.ok(ids.includes(id),'Referenced DOM id exists: '+id);
new vm.Script(js,{filename:'assets/js/pyq-2024-text-quiz.js'});
console.log('PASS TNPSC 2024 full text bank: 200 stems, 1,000 options, final keys, original order and transparent QA status.');
