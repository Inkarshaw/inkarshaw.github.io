// Original-PYQ local digitization workbench: source fidelity and publication isolation.
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
const read=path=>readFileSync(new URL('../'+path,import.meta.url),'utf8');
const html=read('pyq-digitize.html');
const schema=read('assets/js/pyq-draft-schema.js');
const editor=read('assets/js/pyq-digitize.js');
const originalBank=JSON.parse(read('data/quizzes/verified-full-original-papers.json'));
const paperCatalog=JSON.parse(read('data/quizzes/original-paper-practice.json'));
const finalKeys=JSON.parse(read('data/quizzes/original-final-keys.json'));
const hub=read('pyq-hub.html');

assert.equal(originalBank.papers.length,0,'Draft digitization must not publish unapproved originals');
assert.match(html,/noindex,nofollow/,'Staging tool must not be search indexed');
assert.match(html,/No question text is sent to ClearExams or published automatically/);
assert.match(html,/exactly as shown/);
assert.match(html,/assets\/js\/pyq-draft-schema\.js/);
assert.match(html,/assets\/js\/pyq-digitize\.js/);
assert.match(html,/id="localPdf"/);
assert.match(html,/id="exportJson"/);
assert.match(html,/id="importJson"/);
assert.match(html,/id="rawBlock"/);
assert.match(html,/id="sourcePage"/);
assert.match(html,/id="questionPalette"/);
assert.match(html,/id="previewArea"/);
assert.match(html,/id="hasTamil"/);
assert.match(html,/id="hasEnglish"/);
assert.match(editor,/URL\.createObjectURL\(file\)/,'Local source PDFs should not be uploaded');
assert.match(editor,/localStorage/,'Local-only draft persistence required');
assert.match(editor,/publicationStatus:'LOCAL DRAFT/);
assert.match(editor,/kind:'clearexams-local-original-transcription'/);
assert.match(editor,/records\[String\(current\)\]/,'Source question numbers must index drafts');
assert.ok(!editor.includes('innerHTML'),'Do not interpolate original text as arbitrary HTML');
assert.ok(!editor.includes('XMLHttpRequest')&&!editor.includes("method:'POST'"),'No backend transmission');
assert.match(hub,/pyq-digitize\.html/,'PYQ hub must link to the new staging tool');
new vm.Script(editor,{filename:'assets/js/pyq-digitize.js'});
const ctx={window:{}};
vm.runInNewContext(schema,ctx,{timeout:1000});
const api=ctx.window.ClearExamsPYQIntake;
assert.ok(api&&typeof api.examine==='function');
assert.deepEqual(Array.from(api.letters),['A','B','C','D','E']);
let draft=api.newRecord(1,'A/B');
assert.equal(draft.number,1);assert.equal(draft.correctKey,'A/B');
assert.equal(api.examine(draft).captured,false);
draft.originalLanguages=['ta','en'];
draft.sourcePdfPage=3;
draft.originalHasVisuals='no';
for(const lang of ['ta','en']){
 draft.text[lang]='Sample editor input in '+lang;
 for(const l of 'ABCDE')draft.options[lang][l]=lang+' answer '+l;
}
assert.equal(api.examine(draft).captured,true);
assert.equal(api.examine(draft).reviewed,false);
for(const flag of ['text','options','source','key','visuals'])draft.review[flag]=true;
assert.equal(api.examine(draft).reviewed,true);
draft.options.ta.E='';
assert.equal(api.examine(draft).captured,false,'Missing option E rejects complete status');
draft.options.ta.E='Original E';
draft.originalHasVisuals='yes';
assert.equal(api.examine(draft).captured,false,'Missing original diagrams block content capture');
draft.visualPath='assets/pyq-original/paper-001.png';
draft.visualAlt='Source scan figure';
assert.equal(api.examine(draft).reviewed,true);
const restored=api.normalize({...draft,correctKey:'Z'},1,'B/C/D');
assert.equal(restored.correctKey,'B/C/D','Import must not override the matched final-key answer');
assert.equal(restored.text.ta,draft.text.ta,'Do not paraphrase Tamil question');
assert.equal(restored.options.en.A,draft.options.en.A,'Do not rewrite English options');
const tally=api.tally({'1':restored,'2':api.newRecord(2,'C')});
assert.equal(tally.captured,1);assert.equal(tally.reviewed,1);
const actual=paperCatalog.papers.find(p=>p.year===2024);
assert.ok(actual&&actual.questionCount===200);
const key=finalKeys.papers.find(p=>p.id===actual.id);
assert.equal(key.answers.length,200,'Source final key indexed for all original positions');
assert.equal(key.answers[27],'A/B');
assert.equal(key.answers[62],'ALL');
assert.equal(key.answers[153],'ALL');
assert.ok(!/verified-full-original-papers\.json/.test(editor),'Workbench must not auto-write publication manifest');

console.log('Original PYQ digitization workbench: local PDF, 200 numbered slots, Tamil/English + A–E fidelity, source-review controls, safe JSON import/export and publication isolation passed.');
