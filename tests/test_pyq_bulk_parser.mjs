// All-paper bulk split creates source-labelled drafts, not a forged verified exam.
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
const read=p=>readFileSync(new URL('../'+p,import.meta.url),'utf8');
const script=read('assets/js/pyq-bulk-parser.js');
const html=read('pyq-digitize.html'), editor=read('assets/js/pyq-digitize.js');
new vm.Script(script,{filename:'assets/js/pyq-bulk-parser.js'});
const ctx={};vm.runInNewContext(script,ctx);
const parse=ctx.ClearExamsBulkPYQ.parse;
const standard=parse("Exam heading\n1. Which is true?\n(A) Alpha\n(B) Beta\n(C) Gamma\n(D) Delta\n2) Name a region?\nA) North\nB) South\nC) East\nD) West",2);
assert.equal(standard.found,2);
assert.equal(standard.complete,2);
assert.equal(standard.missingNumbers.length,0);
assert.equal(standard.questions[0].options.C,'Gamma');
assert.equal(standard.questions[1].options.D,'West');
assert.ok(standard.questions.every(q=>q.sourceStatus==='bulk-text-draft-unverified'));
assert.equal(standard.answerKeysProvided,false,'Never fill correct answers from extracted text');
const tamil=parse("௧. தமிழ் மொழியின் சிறப்பு என்ன?\n(அ) மொழி\n(ஆ) வரலாறு\n(இ) நாடு\n(ஈ) மக்கள்\n௨. தமிழ் வினா என்ன?\n(அ) ஒன்று\n(ஆ) இரண்டு\n(இ) மூன்று\n(ஈ) நான்கு",2);
assert.equal(tamil.found,2);
assert.equal(tamil.complete,2);
assert.equal(tamil.questions[0].options.A,'மொழி');
assert.equal(tamil.questions[1].options.D,'நான்கு');
const partial=parse("1. Pick any answer?\n(A) Good\n(B) Bad\n2. Another question?\n(A) One\n(B) Two\n(C) Three\n(D) Four",3);
assert.equal(partial.found,2);
assert.equal(partial.complete,1);
assert.equal(partial.incomplete,1);
assert.deepEqual(Array.from(partial.missingNumbers),[3]);
assert.deepEqual(Array.from(partial.questions[0].missingOptions),['C','D']);
assert.match(html,/Fast whole-paper typing/);
assert.match(html,/id="bulkImport"/);
assert.match(html,/id="bulkSourceText"/);
assert.match(html,/id="bulkTextFile"/);
assert.match(html,/assets\/js\/pyq-bulk-parser\.js/);
assert.match(editor,/ClearExamsBulkPYQ\.parse/);
assert.match(editor,/No automatic marks or source certification/);
assert.ok(!editor.includes('innerHTML'));
console.log('Whole-paper bilingual parser: all positions in one operation, missing-option detection, no fabricated final keys.');
