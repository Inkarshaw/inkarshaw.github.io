assert.equal(y22.verifiedSourceCount,60);
assert.equal(y22.secondaryReader,null,'Do not send users to misnumbered coaching-reader pages');
assert.match(y22.sourceAudit,/TNPSC CCS1P\/22 document mirror/);
assert.deepEqual(y22.questions.map(q=>q.number),Array.from({length:130},(_,i)=>i+1));
assert.deepEqual(y22.questions.slice(0,60).map(q=>q.sourcePdfPage),[3,3,4,5,5,6,7,7,8,9,10,10,11,11,12,12,13,13,14,14,15,16,16,17,18,18,19,20,21,22,22,23,24,24,25,25,26,26,27,27,28,28,29,29,30,31,32,32,33,34,34,35,36,37,38,38,39,39,40,40]);
assert.deepEqual(y22.questions.slice(60).map(q=>q.sourcePdfPage),[41,41,42,42,43,43,44,45,45,46,47,47,48,49,49,50,50,51,51,52,52,53,54,55,55,56,57,57,58,58,59,60,60,61,62,63,63,64,65,66]);
assert.equal(y22.sourceNumberedCheckedCount,130);
assert.equal(y22.verifiedSourceCount,60,'Only the first sixty were individually inspected visually');
assert.ok(y22.questions.slice(60).every(q=>q.reviewStatus==='official-tnpsc-pdf-text-page-checked'),'New forty are indexed from official PDF text');
assert.deepEqual(y22.questions.slice(100).map(q=>q.sourcePdfPage),[67,68,69,70,71,71,72,72,73,74,75,75,76,77,78,78,79,79,80,81,81,82,83,84,84,85,85,86,87,88]);
assert.equal(y22.mirroredSourceUrl,'https://previousyearquestions.app/papers/tnpsc-group-1/2022/prelims-general-studies.pdf');
assert.ok(y22.questions.slice(100).every(q=>q.reviewStatus==='original-tnpsc-bilingual-pdf-mirror-visual'),'Each Q101–130 must have original booklet visual review');
assert.ok(y22.questions.slice(100).every(q=>q.keyStatus==='unmapped'&&q.accepted.length===0),'No unverified grading');
assert.match(y22.questions[100].text,/Fundamental Rights/,'Q101 source number');
assert.match(y22.questions[104].text,/habitat/,'Q105 source number');
assert.match(y22.questions[110].text,/ZEBRA/,'Q111 source number');
assert.match(y22.questions[120].text,/VVPAT/,'Q121 source number');
assert.equal(y22.questions[128].editorialPassageSummary,true,'Q129 must declare condensed passage');
assert.match(y22.questions[129].text,/Health System Reform Program/,'Q130 source number');
assert.equal(y22.questions[85].historicClassificationCaution,true,'2022 Q86 needs dated, nonessentialist framing');
assert.match(y22.questions[79].text,/Purna Swaraj/,'Purna Swaraj must occupy official Q80');
